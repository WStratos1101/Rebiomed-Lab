import assert from 'node:assert/strict';
import fs from 'node:fs';
import crypto from 'node:crypto';
import { createTRPCProxyClient, httpBatchLink } from '@trpc/client';
import superjson from 'superjson';
const base = process.env.CF_TEST_URL || 'http://127.0.0.1:8787';
if (!['localhost', '127.0.0.1'].includes(new URL(base).hostname))
    throw new Error('Smoke tests mutate data: only local targets are supported');
const credentials = JSON.parse(fs.readFileSync(process.env.CF_TEST_CREDENTIALS, 'utf8'));
let passed = 0;
const check = (name) => { passed++; console.log(`PASS ${name}`); };
function client() {
    let cookie = '';
    return createTRPCProxyClient({ links: [httpBatchLink({ url: `${base}/api/trpc`, transformer: superjson, fetch: async (input, init) => {
                    const response = await fetch(input, { ...init, headers: { ...init?.headers, ...(cookie ? { cookie } : {}) } });
                    const set = response.headers.get('set-cookie');
                    if (set)
                        cookie = set.split(';')[0];
                    return response;
                } })] });
}
const guest = client(), admin = client(), user = client();
const externalNotification = await fetch(`${base}/api/trpc/system.notifyOwner`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ json: { title: 'Test', content: 'Test' } }) });
assert.equal(externalNotification.status, 404);
check('external notification endpoint removed');
assert.equal((await (await fetch(`${base}/api/health`)).json()).status, 'ok');
check('D1 health');
assert.match(await (await fetch(base)).text(), /Rebiomed Protocol/);
check('frontend HTML');
assert.equal(await guest.auth.me.query(), null);
await assert.rejects(() => guest.team.list.query());
check('anonymous admin access denied');
const content = await guest.content.all.query();
assert.ok(content.protocols.length);
assert.ok(content.protocols[0].updatedAt instanceof Date);
check('protocol data and date serialization');
assert.ok((await guest.chemicals.list.query()).length);
check('chemical recipes');
await admin.auth.adminLogin.mutate({ identifier: credentials.username, password: credentials.password });
assert.equal((await admin.auth.me.query()).role, 'admin');
check('admin scrypt login and session cookie');
const protectedAccount = await admin.auth.me.query();
if (protectedAccount.isSupporter) {
    for (const role of ['admin', 'user'])
        await assert.rejects(() => admin.team.updateRole.mutate({ id: protectedAccount.id, role }));
    for (const approvalStatus of ['pending', 'rejected'])
        await assert.rejects(() => admin.team.updateApproval.mutate({ id: protectedAccount.id, approvalStatus }));
    await assert.rejects(() => admin.team.revokeAccess.mutate({ id: protectedAccount.id }));
    await assert.rejects(() => admin.team.deleteUser.mutate({ id: protectedAccount.id }));
    assert.equal((await admin.auth.me.query()).isSupporter, true);
    check('Supporter API demotion, revocation and deletion denied');
}
const suffix = crypto.randomBytes(6).toString('hex');
const username = `smoke-${suffix}`;
const password = crypto.randomBytes(20).toString('hex');
await guest.auth.register.mutate({ username, name: 'Smoke User', email: `${username}@example.invalid`, password });
await assert.rejects(() => user.auth.userLogin.mutate({ identifier: username, password }));
check('registration requires approval');
const member = (await admin.team.list.query()).find(row => row.username === username);
assert.ok(member);
await admin.team.updateApproval.mutate({ id: member.id, approvalStatus: 'approved' });
await user.auth.userLogin.mutate({ identifier: username, password });
assert.equal((await user.auth.me.query()).username, username);
check('user approval and login');
const revealed = await admin.team.viewPassword.mutate({ id: member.id, currentPassword: credentials.password });
assert.equal(revealed.password, password);
check('encrypted vault compatibility');
const title = `Smoke protocol ${suffix}`;
await admin.content.createDraft.mutate({ kind: 'protocol', title, body: 'Initial version', owner: 'Smoke Admin', category: 'Custom' });
let protocol = (await guest.content.all.query()).protocols.find(row => row.title === title);
assert.ok(protocol);
await user.content.updateDraft.mutate({ kind: 'protocol', id: protocol.id, title, body: 'Pending user revision', owner: 'Smoke User', category: 'Custom' });
assert.ok((await admin.content.pendingEdits.query()).some(row => row.id === protocol.id));
assert.equal((await guest.content.all.query()).protocols.find(row => row.id === protocol.id).summary, 'Initial version');
await admin.content.approvePendingEdit.mutate({ kind: 'protocol', id: protocol.id });
assert.equal((await guest.content.all.query()).protocols.find(row => row.id === protocol.id).summary, 'Pending user revision');
check('pending edit approval');
await user.content.updateDraft.mutate({ kind: 'protocol', id: protocol.id, title, body: 'Second pending revision', owner: 'Smoke User', category: 'Custom' });
await admin.content.updateDraft.mutate({ kind: 'protocol', id: protocol.id, title, body: 'Admin atomic revision', owner: 'Smoke Admin', category: 'Custom' });
assert.ok(!(await admin.content.pendingEdits.query()).some(row => row.id === protocol.id));
assert.equal((await guest.content.all.query()).protocols.find(row => row.id === protocol.id).summary, 'Admin atomic revision');
check('atomic admin update clears stale approval');
await user.experimentLogs.create.mutate({ experimentName: `Smoke experiment ${suffix}`, workDate: '2026-10-18', workDone: 'Test' });
const log = (await user.experimentLogs.list.query()).find(row => row.experimentName === `Smoke experiment ${suffix}`);
assert.ok(log);
assert.ok(!(await admin.experimentLogs.list.query()).some(row => row.id === log.id));
await user.experimentLogs.update.mutate({ id: log.id, experimentName: `Smoke experiment ${suffix}`, result: 'Complete' });
await user.experimentLogs.delete.mutate({ id: log.id });
check('experiment log CRUD and owner isolation');
await user.feedbacks.create.mutate({ category: 'chemical', itemName: `Smoke chemical ${suffix}`, condition: 'Hết hoàn toàn' });
const feedback = (await user.feedbacks.mine.query()).find(row => row.itemName === `Smoke chemical ${suffix}`);
assert.ok(feedback);
const me = await admin.auth.me.query();
await admin.feedbacks.resolve.mutate({ id: feedback.id, handledById: me.id });
await assert.rejects(() => admin.feedbacks.resolve.mutate({ id: feedback.id, handledById: me.id }));
await user.feedbacks.deleteMine.mutate({ id: feedback.id });
check('feedback resolve conflict and deletion');
const sampleTitle = `Smoke sample ${suffix}`;
await guest.content.createDraft.mutate({ kind: 'sample', title: sampleTitle, body: 'Sample draft' });
const sample = (await guest.content.all.query()).samples.find(row => row.name === sampleTitle);
assert.ok(sample);
await guest.content.updateDraft.mutate({ kind: 'sample', id: sample.id, title: sampleTitle, body: 'Updated sample' });
await admin.content.approveSample.mutate({ id: sample.id });
assert.equal((await guest.content.all.query()).samples.find(row => row.id === sample.id).status, 'Đã duyệt');
await admin.content.deleteSample.mutate({ id: sample.id });
check('sample create, update, approve and delete');
const calcName = `Smoke calculator ${suffix}`;
const calcInput = { name: calcName, formula: 'x*2', description: 'Smoke formula', category: 'Custom', inputUnits: { x: 'mL' }, outputUnit: 'mL', variables: [{ key: 'x', label: 'Volume', unit: 'mL' }] };
await admin.content.createCalculator.mutate(calcInput);
const calc = (await guest.content.all.query()).calculators.find(row => row.name === calcName);
assert.ok(calc);
await user.content.updateCalculator.mutate({ ...calcInput, id: calc.id, formula: 'x*3' });
await admin.content.approvePendingEdit.mutate({ kind: 'calculator', id: calc.id });
assert.equal((await guest.content.all.query()).calculators.find(row => row.id === calc.id).formula, 'x*3');
await admin.content.updateCalculator.mutate({ ...calcInput, id: calc.id, formula: 'x*4' });
assert.equal((await guest.content.all.query()).calculators.find(row => row.id === calc.id).formula, 'x*4');
await admin.content.deleteCalculator.mutate({ id: calc.id });
check('calculator formula, pending approval and atomic admin update');
const chemicalInput = { name: `Smoke recipe ${suffix}`, group: 'Smoke', baseVolume: 100, baseUnit: 'mL', stock: '', ingredients: [{ name: 'Water', quantity: 100, unit: 'mL', form: 'liquid' }], method: 'Mix water' };
await guest.chemicals.create.mutate(chemicalInput);
const chemical = (await guest.chemicals.list.query()).find(row => row.name === chemicalInput.name);
assert.ok(chemical);
await admin.chemicals.update.mutate({ ...chemicalInput, id: chemical.dbId, baseVolume: 200 });
await admin.chemicals.approve.mutate({ id: chemical.dbId });
assert.equal((await guest.chemicals.list.query()).find(row => row.dbId === chemical.dbId).baseVolume, 200);
await admin.chemicals.delete.mutate({ id: chemical.dbId });
check('chemical recipe create, update, approve and delete');
await admin.content.adminDeleteProtocol.mutate({ id: protocol.id });
await admin.team.deleteUser.mutate({ id: member.id });
await user.auth.logout.mutate();
assert.equal(await user.auth.me.query(), null);
check('logout');
const cross = await fetch(`${base}/api/trpc/auth.logout`, { method: 'POST', headers: { origin: 'https://other.example', 'content-type': 'application/json' }, body: JSON.stringify({ json: null }) });
assert.equal(cross.status, 403);
check('cross-origin mutation denied');
console.log(`${passed} functional checks passed; temporary user and all test content removed.`);
